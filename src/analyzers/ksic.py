def ksic_levels(code: str | None) -> list[tuple[str, str]]:
    """업종코드 -> [(묶음 키, 이름)] 소분류, 중분류 순. 코드가 없으면 []."""
    code = str(code or "").strip()
    if len(code) < 2 or not code[:2].isdigit():
        return []
    div = KSIC_DIVISION.get(code[:2], f"KSIC {code[:2]}")
    out = []
    if len(code) >= 3:
        out.append((f"ksic3:{code[:3]}", KSIC_GROUP.get(code[:3], f"{div} ({code[:3]})")))
    out.append((f"ksic2:{code[:2]}", div))
    return out
